"""Export captured ARM outcomes and their complete input recipes for C++."""
import json
from pathlib import Path

base = Path(__file__).resolve().parents[1]
data = json.loads((base / 'native_analysis/core_round12/engine_registry/validation.json').read_text())

def array(values):
    return '{' + ','.join(f'{value}U' for value in values) + '}'

lines = ['// Generated by export_engine_registry_fixtures.py from original ARM execution.',
         'const RegistryCase registry_cases[] = {']
for c in data['cases']:
    events = '{' + ','.join('{' + f'Operation::{op},{value}U' + '}' for op, value in c['events']) + '}'
    result = c['result'] + [0] * (3 - len(c['result']))
    fields = [f'Function::{c["function"]}', json.dumps(c['label']), str(c['query']) + 'U',
              array(c['descriptor']), array(c['source']), str(c['base_index']) + 'U',
              str(c['generation']) + 'U', str(c['type']) + 'U', str(c['bank_code']) + 'U',
              str(c['empty']) + 'U', str(c['mismatch']), str(c['callbacks']) + 'U',
              str(c['lazy']).lower(), str(c['ready']).lower(), array(result), events]
    lines.append('    {' + ','.join(fields) + '},')
lines.append('};')
(base / 'native_recovered/tests/engine_registry_fixtures.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Exported', len(data['cases']), 'ARM registry outcomes')
